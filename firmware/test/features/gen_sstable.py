import math
import random

KS = [1, 2, 3, 7, 14, 15, 16, 31, 32, 100, 127, 128, 255, 256, 500, 1000, 1023, 1024,
      2047, 2048, 3000, 4095, 4096, 5000]


def find(T, rng):
    """Return 15 samples in [-2048, 2047] with |sum| <= 14 and sum of squares == T.

    Args:
        T: target sum of squares.
        rng: random.Random instance (deterministic).
    Returns:
        list of 15 ints.
    """
    if T == 0:
        return [0] * 15
    for _ in range(2000000):
        L = min(2047, max(2, int(math.sqrt(3.0 * T / 15) * rng.uniform(1.0, 1.7)) + 2))
        p = rng.uniform(0.05, 1.0) if T < 2000 else 1.0
        v = [rng.randint(-L, L) if rng.random() < p else 0 for _ in range(13)]
        r = rng.randint(-14, 14)
        s = r - sum(v)
        U = T - sum(a * a for a in v)
        disc = 2 * U - s * s
        if U < 0 or disc < 0:
            continue
        q = math.isqrt(disc)
        if q * q != disc or (s + q) % 2:
            continue
        c, e = (s + q) // 2, (s - q) // 2
        if -2048 <= c <= 2047 and -2048 <= e <= 2047:
            row = v + [c, e]
            assert sum(row) == r and sum(a * a for a in row) == T
            return row
    raise SystemExit("no segment found for %d" % T)


